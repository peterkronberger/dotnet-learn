// Local Docusaurus plugin: reads every lesson (a doc with `lesson_id` in its front matter)
// at build time and publishes a small index as global data for the "Lernstand" page.
// Read on the client with usePluginData('lesson-index').
//
// Per lesson: id, docId, title, description, durationMin, goals (the bullet points of the
// ":::note[Lernziele]" box, the single source for learning goals) and the module
// (label and position from the folder's _category_.json). Missing parts stay empty.
const fs = require('fs');
const path = require('path');

const DOC_EXTENSIONS = ['.md', '.mdx'];

function listDocs(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...listDocs(full));
    else if (DOC_EXTENSIONS.includes(path.extname(entry.name))) files.push(full);
  }
  return files;
}

// Flat YAML front matter ("key: value" lines) – enough for the lesson fields.
function parseFrontMatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return {frontMatter: {}, body: text};
  const frontMatter = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let value = kv[2].trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    else if (/^\d+(\.\d+)?$/.test(value)) value = Number(value);
    frontMatter[kv[1]] = value;
  }
  return {frontMatter, body: text.slice(match[0].length)};
}

// Bullet points of the first ":::note[Lernziele…]" box.
function extractGoals(body) {
  const lines = body.split(/\r?\n/);
  const start = lines.findIndex((l) => /^:::note\[Lernziele[^\]]*\]\s*$/.test(l.trim()));
  if (start === -1) return [];
  const goals = [];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (/^:::\s*$/.test(line)) break;
    const bullet = /^[-*]\s+(.*)$/.exec(line);
    if (bullet) goals.push(bullet[1].trim());
  }
  return goals;
}

function readCategory(dir, cache) {
  if (!cache.has(dir)) {
    let category = null;
    const file = path.join(dir, '_category_.json');
    if (fs.existsSync(file)) {
      try {
        category = JSON.parse(fs.readFileSync(file, 'utf8'));
      } catch {
        category = null;
      }
    }
    cache.set(dir, category);
  }
  return cache.get(dir);
}

function loadLessons(docsDir) {
  const categories = new Map();
  const lessons = [];
  for (const file of listDocs(docsDir)) {
    const {frontMatter, body} = parseFrontMatter(fs.readFileSync(file, 'utf8'));
    const lessonId = frontMatter.lesson_id;
    if (typeof lessonId !== 'string' || !lessonId) continue;
    const rel = path.relative(docsDir, file).split(path.sep).join('/');
    const dirName = path.dirname(rel);
    const docId = (dirName === '.' ? '' : `${dirName}/`) + (frontMatter.id || path.basename(rel, path.extname(rel)));
    const category = readCategory(path.dirname(file), categories);
    lessons.push({
      id: lessonId,
      docId,
      title: typeof frontMatter.title === 'string' ? frontMatter.title : lessonId,
      description: typeof frontMatter.description === 'string' ? frontMatter.description : '',
      durationMin: typeof frontMatter.duration_min === 'number' ? frontMatter.duration_min : null,
      goals: extractGoals(body),
      module: {
        label: category && typeof category.label === 'string' ? category.label : '',
        position: category && typeof category.position === 'number' ? category.position : Number.MAX_SAFE_INTEGER,
      },
      position: typeof frontMatter.sidebar_position === 'number' ? frontMatter.sidebar_position : Number.MAX_SAFE_INTEGER,
    });
  }
  // Same order as the autogenerated sidebar: module position, then sidebar_position, then doc id.
  lessons.sort(
    (a, b) => a.module.position - b.module.position || a.position - b.position || a.docId.localeCompare(b.docId),
  );
  const seen = new Set();
  for (const l of lessons) {
    if (seen.has(l.id)) throw new Error(`lesson-index: lesson_id "${l.id}" is used more than once.`);
    seen.add(l.id);
  }
  return lessons;
}

module.exports = function lessonIndexPlugin(context) {
  const docsDir = path.join(context.siteDir, 'docs');
  return {
    name: 'lesson-index',
    async loadContent() {
      return loadLessons(docsDir);
    },
    async contentLoaded({content, actions}) {
      actions.setGlobalData({lessons: content});
    },
    getPathsToWatch() {
      return [path.join(docsDir, '**/*.{md,mdx}'), path.join(docsDir, '**/_category_.json')];
    },
  };
};

module.exports.loadLessons = loadLessons;
